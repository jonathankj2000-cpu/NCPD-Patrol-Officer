"""Bake only the existing 60 VIP terminal coordinates for off-duty scene tests."""
from pathlib import Path
import argparse,hashlib,json,math
ROOT=Path(__file__).resolve().parents[1]
TARGET=ROOT/'bin/x64/plugins/cyber_engine_tweaks/mods/NCPDPatrol/scene_discovery_sites.lua'
def output():
    catalog=json.loads((ROOT/'assets/fixed_markers/catalog.json').read_text())
    selection=json.loads((ROOT/'assets/vip/route-sites.json').read_text())
    excluded={s['existing_marker_bank_index'] for s in json.loads((ROOT/'assets/fixed_markers/location-exclusions.json').read_text())['excluded']}
    by_id={s['index']:s for s in catalog['sites']}
    assert len(selection['sites'])==60 and len({s['site'] for s in selection['sites']})==60
    inputs=['assets/fixed_markers/catalog.json','assets/vip/route-sites.json','assets/fixed_markers/location-exclusions.json']
    revision=hashlib.sha256(b''.join((ROOT/p).read_bytes() for p in inputs)+b'offset-search-v1:10,20,30:8:8:2').hexdigest()
    rows=['-- Generated by tools/build_scene_discovery_catalog.py; factual coordinates from the existing VIP dataset.',
          '-- Developer search anchors only. Never imported into the production dispatch catalogue.',
          'return {revision='+json.dumps(revision)+',coverage="60 terminal anchors across six districts",sites={']
    for item in selection['sites']:
        row=by_id[item['site']];p=row['position']
        assert row['kind']=='terminal' and row['source_id']==item['source_id'] and row['index'] not in excluded
        assert all(math.isfinite(p[k]) and abs(p[k])<100000 for k in 'xyz')
        rows.append(' {id=%s,label=%s,source_id=%s,source_index=%d,district=%s,x=%.9f,y=%.9f,z=%.9f,heading=0},'%(
            json.dumps('terminal_'+str(row['index'])),json.dumps(item['name']),json.dumps(row['source_id']),row['index'],json.dumps(item['district']),p['x'],p['y'],p['z']))
    rows.append('}}\n');return '\n'.join(rows)
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();body=output()
    if a.check:assert TARGET.read_text()==body
    else:TARGET.write_text(body)
    print('PASS: 60 discovery anchors match the existing VIP coordinate dataset; excluded H10 absent')
if __name__=='__main__':main()
