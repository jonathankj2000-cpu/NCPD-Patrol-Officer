"""Bake repeatable VIP endpoint pairs from the existing native marker catalogue.

No network, game discovery state, journal rebuild or road path generation.
Runtime coordinates come from marker_catalog.lua, never from a second XYZ list.
"""
from pathlib import Path
import argparse
import hashlib
import json
import math
import random

ROOT = Path(__file__).resolve().parents[1]
AUTHORING = 'assets/vip/route-sites.json'
MANIFEST = 'assets/vip/routes.json'
MODULE = 'bin/x64/plugins/cyber_engine_tweaks/mods/NCPDPatrol/vip_route_catalog.lua'


def build(root=ROOT):
    spec = json.loads((root / AUTHORING).read_text())
    catalog = json.loads((root / spec['source_catalog']).read_text())
    sites = {s['index']: s for s in catalog['sites']}
    allowed = spec['sites']
    assert spec['schema'] == 1 and spec['destinations_per_pickup'] == 6
    assert len({s['site'] for s in allowed}) == len(allowed)
    excluded = {s['existing_marker_bank_index'] for s in
                json.loads((root / spec['exclusions']).read_text())['excluded']}

    def distance(a, b):
        return math.dist(tuple(a[k] for k in 'xyz'), tuple(b[k] for k in 'xyz'))

    for entry in allowed:
        site = sites[entry['site']]
        assert site['kind'] == 'terminal' and site['source_id'] == entry['source_id']
        assert site['node_ref'] and 'dataterm' in site['source_id']
        assert entry['site'] not in excluded
        assert not site['source_id'].startswith('dlc6_apart_')
        assert all(math.isfinite(v) for v in site['position'].values())
        # The unchanged runtime matcher must resolve this exact ID, including
        # against metro aliases outside our candidate list. Never widen 2 m.
        nearest = min((s for s in sites.values() if s['kind'] == 'terminal'),
                      key=lambda s: distance(site['position'], s['position']))
        assert nearest['index'] == entry['site'], ('ambiguous endpoint', entry)

    routes = []
    for entry in allowed:
        pickup = sites[entry['site']]
        start = pickup['position']
        rng = random.Random(spec['seed'] + entry['site'])
        candidates = []
        for other in allowed:
            point = sites[other['site']]['position']
            metres = distance(start, point)
            if spec['trip_min_metres'] <= metres <= spec['trip_max_metres']:
                heading = int((math.atan2(point['y'] - start['y'], point['x'] - start['x'])
                               + math.pi) / (math.pi / 3)) % 6
                candidates.append((other['site'], metres, heading, rng.random()))
        used, headings = set(), set()
        # Varied straight-line lengths/directions, not authored driving routes.
        for target in (1000, 1600, 2200, 2800, 3600, 4500):
            choices = [c for c in candidates if c[0] not in used]
            assert choices, ('insufficient destinations', entry['site'])
            drop, metres, heading, _ = min(choices, key=lambda c:
                (abs(c[1] - target) + (300 if c[2] in headings else 0), c[3], c[0]))
            used.add(drop)
            headings.add(heading)
            routes.append({'id': f'vip_{entry["site"]}_{drop}', 'pickup': entry['site'],
                           'delivery': drop, 'straight_line_metres': round(metres, 3)})
        assert any(800 <= r['straight_line_metres'] <= 2500
                   for r in routes if r['pickup'] == entry['site'])
    assert len({r['id'] for r in routes}) == len(routes)
    inputs = [AUTHORING, spec['source_catalog'], spec['sources'], spec['exclusions']]
    manifest = {'schema': 1, 'endpoint_count': len(allowed), 'route_count': len(routes),
                'coordinates': 'Canonical marker_catalog.lua rows by site ID; no duplicated runtime XYZ',
                'authored_inputs': {p: hashlib.sha256((root / p).read_bytes()).hexdigest() for p in inputs},
                'validation': spec['validation'], 'routes': routes}
    lines = ['-- Generated by tools/build_vip_route_catalog.py; edit assets/vip/route-sites.json.',
             '-- Fixed endpoint IDs only. Positions are read from marker_catalog.lua.',
             'return {schema=1, recentSelections=' + str(spec['recent_selections']) + ', sites={',
             '    ' + ','.join(str(s['site']) for s in allowed), '}, routes={']
    lines.extend('    {' + str(r['pickup']) + ',' + str(r['delivery']) + '},' for r in routes)
    lines.append('}}')
    return {MANIFEST: json.dumps(manifest, indent=2) + '\n', MODULE: '\n'.join(lines) + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = build()
    for name, content in outputs.items():
        if args.check:
            assert (ROOT / name).read_text() == content, 'Regenerate VIP routes: ' + name
        else:
            (ROOT / name).write_text(content)
    print('PASS: deterministic VIP route catalogue' + (' matches checked-in output' if args.check else ' generated'))


if __name__ == '__main__':
    main()
